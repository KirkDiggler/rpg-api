// benchKeys are the benchmark keep's two fixtures (rpg-project#740, plan
// G6): keep scale and the 30k ceiling. They are the only fixtures these
// tests name; no count of shelf files is pinned.
var benchKeys = []string{"bench-keep", "bench-keep-30k"}

// benchDir is where the fixtures are kept: a subdirectory of the content
// directory, which NewFileRegistry does not read, so a default boot does not
// compile and project them. The benchmark harness copies them onto its own
// environment's shelf. See the open question on rpg-project#749.
func benchDir(t *testing.T) string {
	t.Helper()

	return filepath.Join(dungeonstest.ContentDir(t), "bench")
}

// TestBenchFixtures_MatchGenerator is the fixtures' currency (plan B9): each
// file, regenerated by the pinned encounter module's keepgen from the options
// its own header records, is byte-for-byte the file in the repository. Bytes,
// header included, deliberately: the header is part of the artifact the
// harness copies. A repin that shifts the generator's output fails here until
// both files are regenerated with the command in their headers; never edit
// them by hand.
func TestBenchFixtures_MatchGenerator(t *testing.T) {
	for _, key := range benchKeys {
		t.Run(key, func(t *testing.T) {
			file, err := os.ReadFile(filepath.Join(benchDir(t), key+".yaml")) //nolint:gosec // fixed test path
			require.NoError(t, err)

			opts, err := keepgen.OptionsFromHeader(file)
			require.NoError(t, err, "the file's header records its options")
			require.Equal(t, key, opts.Key, "the recorded key is the file's name")

			regenerated, report, err := keepgen.Generate(keepgen.DefaultPlan(), opts)
			require.NoError(t, err)
			t.Logf("%s: %d bytes; %s", key, len(file), report)

			// Not require.Equal: a diff of two half-megabyte slices helps no one.
			require.Truef(t, bytes.Equal(file, regenerated),
				"content/bench/%s.yaml (%d bytes) is not the pinned keepgen's output (%d bytes); "+
					"regenerate it with the command in its header", key, len(file), len(regenerated))
		})
	}
}

// TestBenchFixtures_ListOnAShelf is the other half of B9: copied onto a shelf
// beside the default dungeon, as the harness does, both fixtures compile and
// project, are served as single-room sites (so ListDungeons carries them),
// and the registry's load report counts them.
func TestBenchFixtures_ListOnAShelf(t *testing.T) {
	shelf := t.TempDir()
	stage := func(src string) {
		raw, err := os.ReadFile(src) //nolint:gosec // fixed test paths
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(shelf, filepath.Base(src)), raw, 0o600))
	}
	stage(filepath.Join(dungeonstest.ContentDir(t), dungeons.DefaultKey+".yaml"))
	for _, key := range benchKeys {
		stage(filepath.Join(benchDir(t), key+".yaml"))
	}

	r, err := dungeons.NewFileRegistry(shelf, dungeonstest.Projector(t))
	require.NoError(t, err)

	list, err := r.List(context.Background())
	require.NoError(t, err)
	listed := map[string]bool{}
	for _, s := range list {
		listed[s.Key] = true
	}
	for _, key := range benchKeys {
		require.Truef(t, listed[key], "%s is on the shelf", key)
		e, err := r.Get(context.Background(), key)
		require.NoError(t, err)
		require.Truef(t, e.SingleRoom, "%s is a single-room site, so the lobby lists it", key)
	}

	load := r.LoadReport()
	require.Equal(t, len(list), load.Files, "the load report counts every file the registry holds")
	require.Positive(t, load.Elapsed)
	t.Logf("content registry: compiled %d files in %.2fms", load.Files, float64(load.Elapsed.Microseconds())/1000)
}
